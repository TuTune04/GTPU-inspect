/* Khóa chú giải cho một trường trong lưới octet. */
window.glossaryKey = function (layerKey, fieldName) {
  const layer = layerKey === "inner" ? "ip" : layerKey;
  const name = fieldName.replace(/^#\d+ /, "");
  return layer + "." + (/^(Flag|Bit) \d$/.test(name) ? "flags" : name);
};
